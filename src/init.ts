// orq init: install orqestrai into one project. The source keeps skills in groups
// (skills/<group>/<name>/); the project gets them flat, under their frontmatter names,
// in .claude/skills/<name>/. Everything orq init writes starts with "orq-" and is replaced
// on the next run; anything else in .claude/ is the project's and stays as it is.
import { Effect } from "effect"
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs"
import { basename, join } from "node:path"
import { OrqError } from "./domain.ts"

const PREFIX = "orq-"
const NOTE = "<!-- generated by orq init from orqestrai. Edit it in orqestrai, not here. -->"
const GUARD = { type: "command", command: "orq guard", timeout: 10 }
const GUARD_MATCHER = "Bash|Read|Grep|Glob|Write|Edit|MultiEdit|NotebookEdit"

/** The `name:` in a Markdown file's frontmatter. */
const nameOf = (file: string) => /^---\n(?:[\s\S]*?\n)?name:\s*(\S+)/.exec(readFileSync(file, "utf8"))?.[1]

/** Puts the generated note after the frontmatter, or at the top when there is none. */
const markGenerated = (file: string) => {
  const text = readFileSync(file, "utf8")
  const fm = /^---\n[\s\S]*?\n---\n/.exec(text)
  writeFileSync(file, fm ? `${fm[0]}${NOTE}\n${text.slice(fm[0].length)}` : `${NOTE}\n\n${text}`)
}

const markdownIn = (dir: string): string[] =>
  readdirSync(dir).flatMap((f) => {
    const p = join(dir, f)
    return statSync(p).isDirectory() ? markdownIn(p) : p.endsWith(".md") ? [p] : []
  })

/** Every skill folder in the source: skills/<group>/<name>/SKILL.md. */
const sourceSkills = (orqRoot: string) =>
  readdirSync(join(orqRoot, "skills")).flatMap((group) =>
    readdirSync(join(orqRoot, "skills", group))
      .map((s) => join(orqRoot, "skills", group, s))
      .filter((d) => existsSync(join(d, "SKILL.md"))),
  )

const removeOurs = (dir: string, keep: (f: string) => boolean = () => true) => {
  if (!existsSync(dir)) return
  for (const f of readdirSync(dir)) if (f.startsWith(PREFIX) && keep(f)) rmSync(join(dir, f), { recursive: true, force: true })
}

const installSkills = (orqRoot: string, project: string) => {
  const target = join(project, ".claude", "skills")
  removeOurs(target)
  const names: string[] = []
  for (const src of sourceSkills(orqRoot)) {
    const name = nameOf(join(src, "SKILL.md"))
    if (!name?.startsWith(PREFIX)) throw new Error(`${src}/SKILL.md: name must start with ${PREFIX}`)
    const out = join(target, name)
    cpSync(src, out, { recursive: true })
    for (const md of markdownIn(out)) markGenerated(md)
    names.push(name)
  }
  return names
}

const installAgents = (orqRoot: string, project: string) => {
  const target = join(project, ".claude", "agents")
  mkdirSync(target, { recursive: true })
  removeOurs(target, (f) => f.endsWith(".md"))
  const names: string[] = []
  for (const f of readdirSync(join(orqRoot, "agents")).filter((f) => f.endsWith(".md"))) {
    const name = nameOf(join(orqRoot, "agents", f)) ?? basename(f, ".md")
    if (!name.startsWith(PREFIX)) throw new Error(`agents/${f}: name must start with ${PREFIX}`)
    const out = join(target, `${name}.md`)
    cpSync(join(orqRoot, "agents", f), out)
    markGenerated(out)
    names.push(name)
  }
  return names
}

type HookEntry = { matcher?: string; hooks: { type: string; command: string; timeout?: number }[] }

/** Adds the guard hook to .claude/settings.json once, and keeps every other setting. */
const installHook = (project: string) => {
  const file = join(project, ".claude", "settings.json")
  const settings = existsSync(file) ? (JSON.parse(readFileSync(file, "utf8")) as Record<string, any>) : {}
  settings.hooks ??= {}
  const entries = ((settings.hooks.PreToolUse ?? []) as HookEntry[])
    .map((e) => ({ ...e, hooks: e.hooks.filter((h) => h.command !== GUARD.command) }))
    .filter((e) => e.hooks.length > 0)
  settings.hooks.PreToolUse = [...entries, { matcher: GUARD_MATCHER, hooks: [GUARD] }]
  writeFileSync(file, `${JSON.stringify(settings, null, 2)}\n`)
}

const installConfig = (project: string, base: string) => {
  const dir = join(project, ".orqestrai")
  mkdirSync(dir, { recursive: true })
  const cfg = join(dir, "config.toml")
  if (!existsSync(cfg)) writeFileSync(cfg, `base_branch = "${base}"\n`)
}

export const install = (orqRoot: string, project: string, base: string) =>
  Effect.try({
    try: () => {
      mkdirSync(join(project, ".claude"), { recursive: true })
      installConfig(project, base)
      const skills = installSkills(orqRoot, project)
      const agents = installAgents(orqRoot, project)
      installHook(project)
      return { skills, agents }
    },
    catch: (e) => new OrqError({ message: `init: ${e instanceof Error ? e.message : String(e)}` }),
  })
