// orq init through the command line: what a project gets in .orqestrai/ and .claude/.
import { afterEach, beforeEach, describe, expect, test } from "bun:test"
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { tmpdir } from "node:os"
import { join, resolve } from "node:path"

const CLI = resolve(import.meta.dir, "..", "src", "cli.ts")
let dir: string, repo: string

const orq = (args: string[], cwd = repo) => {
  const env = { ...process.env, ORQ_HOME: join(dir, "home") }
  const p = Bun.spawnSync(["bun", CLI, ...args], { cwd, env, stdout: "pipe", stderr: "pipe" })
  return { code: p.exitCode, out: p.stdout.toString(), err: p.stderr.toString() }
}
const read = (p: string) => readFileSync(join(repo, p), "utf8")
const settings = () => JSON.parse(read(".claude/settings.json"))
const guardHooks = () =>
  (settings().hooks.PreToolUse as { hooks: { command: string }[] }[]).filter((e) => e.hooks.some((h) => h.command === "orq guard"))

beforeEach(() => {
  dir = mkdtempSync(join(tmpdir(), "orq-init-"))
  repo = join(dir, "proj")
  mkdirSync(repo)
  Bun.spawnSync(["git", "init", "-q", "-b", "main"], { cwd: repo })
})
afterEach(() => rmSync(dir, { recursive: true, force: true }))

describe("orq init", () => {
  test("installs the skills flat, each under its own name", () => {
    expect(orq(["init"]).code).toBe(0)
    const skills = readdirSync(join(repo, ".claude/skills")).sort()
    expect(skills).toContain("orq-triage")
    expect(skills).toContain("orq-principle-test-behavior")
    expect(skills).toContain("orq-problem-class")
    expect(skills.every((s) => s.startsWith("orq-"))).toBe(true)
    expect(skills).not.toContain("orq-archetypes") // drafts are not installed
    expect(read(".claude/skills/orq-triage/SKILL.md")).toMatch(/^---\nname: orq-triage\n/)
  })

  test("copies a skill's other files and marks every file as generated", () => {
    orq(["init"])
    expect(existsSync(join(repo, ".claude/skills/orq-principle-test-behavior/GUIDELINES.md"))).toBe(true)
    expect(read(".claude/skills/orq-plan/SKILL.md")).toContain("generated by orq init")
    expect(read(".claude/agents/orq-researcher.md")).toMatch(/^---\nname: orq-researcher\n[\s\S]*generated by orq init/)
  })

  test("creates .orqestrai/config.toml with the base branch, and keeps an existing one", () => {
    orq(["init"])
    expect(read(".orqestrai/config.toml")).toContain('base_branch = "main"')
    expect(read(".orqestrai/config.toml")).toContain("[commands]") // the quality gate's commands, to fill in
    writeFileSync(join(repo, ".orqestrai/config.toml"), 'base_branch = "develop"\n')
    orq(["init"])
    expect(read(".orqestrai/config.toml")).toBe('base_branch = "develop"\n')
  })

  test("adds the guard hook to .claude/settings.json and keeps what is there", () => {
    mkdirSync(join(repo, ".claude"))
    writeFileSync(
      join(repo, ".claude/settings.json"),
      JSON.stringify({ model: "opus", hooks: { PreToolUse: [{ matcher: "Bash", hooks: [{ type: "command", command: "mine.sh" }] }] } }),
    )
    orq(["init"])
    expect(settings().model).toBe("opus")
    expect(JSON.stringify(settings())).toContain("mine.sh")
    expect(guardHooks()).toHaveLength(1)
  })

  test("running it again replaces its own files, not the project's", () => {
    orq(["init"])
    mkdirSync(join(repo, ".claude/skills/orq-old"), { recursive: true })
    mkdirSync(join(repo, ".claude/skills/my-skill"), { recursive: true })
    orq(["init"])
    expect(existsSync(join(repo, ".claude/skills/orq-old"))).toBe(false)
    expect(existsSync(join(repo, ".claude/skills/my-skill"))).toBe(true)
    expect(guardHooks()).toHaveLength(1)
  })

  test("warns when orq is not on PATH, because the guard hook calls it by name", () => {
    const env = { ...process.env, ORQ_HOME: join(dir, "home"), PATH: "/usr/bin:/bin" }
    const p = Bun.spawnSync([process.execPath, CLI, "init"], { cwd: repo, env, stdout: "pipe", stderr: "pipe" })
    expect(p.exitCode).toBe(0)
    expect(p.stderr.toString()).toContain("orq is not on PATH")
  })

  test("fails outside a git repository", () => {
    const r = orq(["init"], dir)
    expect(r.code).toBe(1)
    expect(r.err).toContain("orq: not in a git repository")
  })
})
